# What is a Conditional Statement?
# Conditional statements help a program make decisions by executing different blocks of code based
# on conditions.

# Types of Conditional Statements
# 1 if
# 2 if-else
# 3 if-elif-else
# 4 nested if


# # 1. if Statement
# # Executes code only if condition is True.
# x = 15
# if x > 10:
#  print("x is greater than 10")


# # 2. if-else Statement
# # Executes one block if True, another if False.
# x = 7
# if x % 2 == 0:
#  print("Even")
# else:
#  print("Odd")


# # 3. if-elif-else Statement
# # Used for multiple conditions.
# x = -3
# if x > 0:
#  print("Positive")
# elif x == 0:
#  print("Zero")
# else:
#  print("Negative")


# # 4. Nested if
# # An if inside another if.
# x = 8
# if x > 0:
#  if x % 2 == 0:
#  print("Positive Even")


